import { useState, useEffect, useRef } from 'react';
import { TournamentFormat, GridlockQuestion, HexTile, GridlockGameState } from '../types/gridlockTypes';
import { generateAiGridlockQuestions, build5x5HexGridFromQuestions } from '../services/gridlockAiGenerator';
import { buildMultiRoundQuestionBank } from '../factories/multiRoundQuestionBank';
import { LessonChunk, ModuleScheme } from '../../../../../types';

export const useGridlockSetupState = (
  lessonTitle: string,
  chunks: LessonChunk[] = [],
  moduleScheme?: ModuleScheme
) => {
  const [tournamentFormat, setTournamentFormat] = useState<TournamentFormat>('best-of-3');
  const [goldHexCount, setGoldHexCount] = useState<number>(2);
  const [roomCode] = useState<string>(() => {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    let code = '';
    for (let i = 0; i < 4; i++) code += chars.charAt(Math.floor(Math.random() * chars.length));
    return code;
  });

  const [questions, setQuestions] = useState<GridlockQuestion[]>(() =>
    buildMultiRoundQuestionBank(lessonTitle || 'Class Lesson', chunks, 'best-of-7').flat()
  );

  const [grid, setGrid] = useState<HexTile[][]>(() =>
    build5x5HexGridFromQuestions(questions, 2, true, lessonTitle, chunks)
  );

  const [isGenerating, setIsGenerating] = useState(false);
  const [isSimulatorOpen, setIsSimulatorOpen] = useState(false);
  const [isPreFlightOpen, setIsPreFlightOpen] = useState(false);
  const [isProjectorOpen, setIsProjectorOpen] = useState(false);
  const [isAttached, setIsAttached] = useState(() => Boolean(sessionStorage.getItem('attached_gridlock_game')));
  const autoGeneratedRef = useRef(false);

  const reshuffleBoard = () => {
    setGrid(build5x5HexGridFromQuestions(questions, goldHexCount, true, lessonTitle, chunks));
  };

  const generateAi = async (scheme?: ModuleScheme) => {
    setIsGenerating(true);
    try {
      const allRounds = await generateAiGridlockQuestions({
        lessonTitle,
        chunks,
        moduleScheme: scheme || moduleScheme,
        format: tournamentFormat,
      });
      setQuestions(allRounds);
      setGrid(build5x5HexGridFromQuestions(allRounds, goldHexCount, true, lessonTitle, chunks));
      return { success: true, count: allRounds.length };
    } catch {
      return { success: false, count: 0 };
    } finally {
      setIsGenerating(false);
    }
  };

  useEffect(() => {
    if (!autoGeneratedRef.current && lessonTitle) {
      autoGeneratedRef.current = true;
      generateAi(moduleScheme);
    }
  }, [lessonTitle]);

  const activeGameState: GridlockGameState = {
    roomCode,
    lessonTitle,
    status: 'in_game',
    scores: { redWins: 0, blueWins: 0, currentMatch: 1, format: tournamentFormat },
    grid,
    activeTileId: grid[2]?.[2]?.id || grid[0]?.[0]?.id || null,
    players: [],
    config: { roomCode, lessonTitle, tournamentFormat, goldHexCount, allowFuzzyMatching: true, isLive: true },
  };

  return {
    tournamentFormat,
    setTournamentFormat,
    goldHexCount,
    setGoldHexCount,
    roomCode,
    questions,
    setQuestions,
    grid,
    setGrid,
    reshuffleBoard,
    generateAi,
    activeGameState,
    isGenerating,
    isSimulatorOpen,
    setIsSimulatorOpen,
    isPreFlightOpen,
    setIsPreFlightOpen,
    isProjectorOpen,
    setIsProjectorOpen,
    isAttached,
    setIsAttached,
  };
};
