import { SummativeTaskChoice } from './typesSummative';

export function downloadTaskHandout(task: SummativeTaskChoice, lessonTitle: string) {
  const content = `# Summative Assessment Handout: ${task.title}
Lesson: ${lessonTitle || 'Applied Practical Skills'}
Format: ${task.formatLabel} (20 Minutes)
Criteria Assessed: ${task.criteriaCodes.join(', ') || 'N/A'}
Concepts Covered: ${task.coveredConcepts.join(', ') || 'General Core'}

---
## Student Brief
${task.description}

## Handout Instructions & Task Prompts
${task.handoutPrompt}

---
Generated by Lesson Planning Wizard
`;

  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `${task.formatLabel.replace(/\s+/g, '_')}_Handout.md`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
